export type MessageKey = keyof typeof COPY;
export type MessageValues = Record<string, string | number>;

export function isUiLocale(value: unknown): value is UiLocale {
  return value === "zh-CN" || value === "en";
}

export function translate(locale: UiLocale, key: MessageKey, values: MessageValues = {}): string {
  const entry = COPY[key];
  const template = locale === "zh-CN" ? entry.zh : entry.en;
  return Object.entries(values).reduce(
    (output, [name, value]) => output.replaceAll(`{{${name}}}`, String(value)),
    template,
  );
}
